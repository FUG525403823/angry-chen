import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, rmSync, cpSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { treeFingerprint, verifyAdmission, auditRelease } from './codely-dependencies.mjs';
import { verifyArchive, verifyArchivePaths, listArchive, extractArchive } from './codely-fetch.mjs';
import { createHash } from 'node:crypto';
const root = mkdtempSync(join(tmpdir(), 'ac-codely-admission-'));
try {
  mkdirSync(join(root, 'tools')); mkdirSync(join(root, 'vendor')); mkdirSync(join(root, 'stage'));
  writeFileSync(join(root, 'vendor/package.json'), JSON.stringify({ name: 'cn.tuanjie.codely.bridge', version: '1.0.87' }));
  writeFileSync(join(root, 'vendor/plugin.bin'), 'vendor native fixture');
  const fp = treeFingerprint(join(root, 'vendor'));
  const entry = { name: 'cn.tuanjie.codely.bridge', version: '1.0.87', manifestValue: '1.0.87', lockSource: 'registry', registry: 'https://packages.tuanjie.cn', path: 'vendor', files: fp.files, treeSha256: fp.sha256, dependencies: {} };
  const record = { schema: 1, scope: 'development-only-excluded-from-player', packages: [entry], additionalLock: {}, forbiddenPlayerNames: ['TJGenerators.Runtime.dll'] };
  writeFileSync(join(root, 'tools/codely-admission.json'), JSON.stringify(record));
  const manifest = { dependencies: { [entry.name]: entry.manifestValue } }, lock = { dependencies: { [entry.name]: { version: entry.version, source: entry.lockSource, url: entry.registry, dependencies: {} } } };
  assert(verifyAdmission(root, manifest, lock).has(entry.name)); console.log('PASS exact package positive');
  const badManifest = structuredClone(manifest); badManifest.dependencies[entry.name] = '1.0.88';
  assert.throws(() => verifyAdmission(root, badManifest, lock), /Manifest/); console.log('PASS version drift rejected');
  const badLock = structuredClone(lock); badLock.dependencies[entry.name].url = 'https://attacker.invalid';
  assert.throws(() => verifyAdmission(root, manifest, badLock), /Lock/); console.log('PASS source drift rejected');
  writeFileSync(join(root, 'vendor/plugin.bin'), 'modified same version');
  assert.throws(() => verifyAdmission(root, manifest, lock), /fingerprint/); console.log('PASS same-version mutation rejected');
  writeFileSync(join(root, 'vendor/plugin.bin'), 'vendor native fixture');
  writeFileSync(join(root, 'vendor/no-extension-native'), 'extra executable');
  assert.throws(() => verifyAdmission(root, manifest, lock), /fingerprint/); console.log('PASS extra extensionless file rejected');
  rmSync(join(root, 'vendor/no-extension-native'));
  assert.throws(() => auditRelease(root, join(root, 'stage')), /empty/); console.log('PASS empty release stage rejected');
  writeFileSync(join(root, 'stage/player.exe'), 'fixture player, not vendor');
  assert(auditRelease(root, join(root, 'stage')).pass); console.log('PASS clean release stage');
  cpSync(join(root, 'vendor/plugin.bin'), join(root, 'stage/renamed.bin'));
  assert.throws(() => auditRelease(root, join(root, 'stage')), /leaked/); console.log('PASS renamed vendor content rejected');
  rmSync(join(root, 'stage/renamed.bin'));
  writeFileSync(join(root, 'stage/TJGenerators.Runtime.dll'), 'new build different bytes');
  assert.throws(() => auditRelease(root, join(root, 'stage')), /leaked/); console.log('PASS runtime assembly identity name rejected');
  rmSync(join(root, 'stage/TJGenerators.Runtime.dll'));
  const closure = structuredClone(lock); closure.dependencies[entry.name].dependencies.unknown = '1.0.0';
  assert.throws(() => verifyAdmission(root, manifest, closure), /closure/); console.log('PASS dependency closure drift rejected');
  const optional = { 'generated.meta': createHash('sha256').update('known meta').digest('hex') };
  writeFileSync(join(root, 'vendor/generated.meta'), 'known meta');
  assert.deepEqual(treeFingerprint(join(root, 'vendor'), optional), fp);
  writeFileSync(join(root, 'vendor/generated.meta'), 'changed meta');
  assert.throws(() => treeFingerprint(join(root, 'vendor'), optional), /metadata changed/);
  rmSync(join(root, 'vendor/generated.meta')); console.log('PASS only exact generated metadata optional');
  const archive = { kind: 'zip', url: 'https://official.invalid/file.zip', sha256: createHash('sha256').update('archive fixture').digest('hex') };
  assert.equal(verifyArchive(Buffer.from('archive fixture'), archive), archive.sha256);
  assert.throws(() => verifyArchive(Buffer.from('changed archive'), archive), /digest changed/);
  verifyArchivePaths('package/package.json\npackage/file\n');
  for (const unsafe of ['../escape', '/absolute', 'C:\\escape', 'package/../../escape', 'package\\..\\escape', '']) assert.throws(() => verifyArchivePaths(unsafe), /Unsafe/);
  console.log('PASS archive digest and traversal contract');
  // Real ZIP bytes with forward-slash names, including a directory entry. This exercises the
  // platform extractor (bsdtar on Windows, unzip where GNU tar cannot read ZIP) in CI.
  const zipPath = join(root, 'fixture.zip');
  writeFileSync(zipPath, Buffer.from('UEsDBBQAAAAAALttZV0AAAAAAAAAAAAAAAAIAAAAcGFja2FnZS9QSwMEFAAAAAgAu21lXburVo4UAAAAEgAAABQAAABwYWNrYWdlL3BhY2thZ2UuanNvbqtWykvMTVWyUkrLrCgpLUpVqgUAUEsDBBQAAAAIALttZV2GphA2BwAAAAUAAAARAAAAcGFja2FnZS9oZWxsby50eHTLSM3JyQcAUEsBAhQAFAAAAAAAu21lXQAAAAAAAAAAAAAAAAgAAAAAAAAAAAAAAAAAAAAAAHBhY2thZ2UvUEsBAhQAFAAAAAgAu21lXburVo4UAAAAEgAAABQAAAAAAAAAAAAAAAAAJgAAAHBhY2thZ2UvcGFja2FnZS5qc29uUEsBAhQAFAAAAAgAu21lXYamEDYHAAAABQAAABEAAAAAAAAAAAAAAAAAbAAAAHBhY2thZ2UvaGVsbG8udHh0UEsFBgAAAAADAAMAtwAAAKIAAAAAAA==', 'base64'));
  const archiveListing = listArchive('zip', zipPath);
  verifyArchivePaths(archiveListing);
  assert.match(archiveListing, /package\/package\.json/);
  assert.match(archiveListing, /package\/hello\.txt/);
  const unpacked = join(root, 'zip-unpacked');
  mkdirSync(unpacked);
  extractArchive('zip', zipPath, unpacked);
  assert.equal(readFileSync(join(unpacked, 'package/package.json'), 'utf8'), '{"name":"fixture"}');
  assert.equal(readFileSync(join(unpacked, 'package/hello.txt'), 'utf8'), 'hello');
  console.log('PASS ZIP listing and extraction');
  rmSync(join(root, 'vendor'), { recursive: true });
  assert.throws(() => verifyAdmission(root, manifest, lock), /ENOENT/); console.log('PASS missing package rejected');
} finally { rmSync(root, { recursive: true, force: true }); }
